# -*- coding: utf-8 -*-
"""
Fig. 4.1-2 representative structure fields (one porosity scale for all four panels), first version 2026-10-27.

    powershell -File scripts\\run_local.ps1 figures\\ch4\\fig_4_1_2.py

Fields are generated by the case modules exactly as in the chapter-5 runs (no new results):
(a) porosity gradient, n linear in elevation, bottom 0.12 / top 0.30 (cases/inclined_hole_gradient via
    inclined_hole_channel.G.phi_field("gradient"), 1.25 m);
(b) through-going channel, the collar channel n 0.45 on background 0.18, width 2.5 m (inclined_hole_channel.field
    "band", band_x = BAND_X_COLLAR; one of the positions / porosities of the channel cases);
(c) random field, mean 0.18, s.d. 0.06, realisation 1 (field "random", seed 1, 2.5 m);
(d) boulder bridge local model, variant A (outputs/rerun_rate/D/boulder/final_A.npz): 16 m x 16 m, cap 4 m x 1 m and
    two 1 m x 2 m supports (dark grey) around the concave space below the boulder, background 0.18.
(a)-(c) share axes relative to the hole mouth; the hole is drawn as an outflow section over its full length (the
chapter-5 line source). Colour scale saturates at 0.45 (random-field values above 0.45 drawn alike).
"""
from __future__ import print_function

import imp
import os

import numpy as np
from matplotlib.colors import LinearSegmentedColormap, ListedColormap

import ch4fig as F
from ch4fig import K, plt

C = imp.load_source("inclined_hole_channel", os.path.join(K.REPO, "cases", "inclined_hole_channel.py"))
G = C.G
PHI_CMAP = LinearSegmentedColormap.from_list("phi", ["#fff7e0", "#f2c879", "#d98b2b", "#8a4b0f"])
VMAX = 0.45


def show(ax, x, y, phi, cell, x0, y0, solid=None):
    g, ext = K.grid(x, y, phi, cell)
    e = K.rel(ext, x0, y0)
    im = ax.imshow(g, origin="lower", extent=e, cmap=PHI_CMAP, vmin=0.0, vmax=VMAX, interpolation="nearest")
    if solid is not None:
        gs, _ = K.grid(x, y, solid.astype(float), cell)
        ax.imshow(np.ma.masked_where(gs < 0.5, gs), origin="lower", extent=e, cmap=ListedColormap([F.SOLID]),
                  interpolation="nearest")
    ax.set_aspect("equal")
    return im


def mesh(cell):
    G.CELL = cell
    _, x, y, _, _ = G.build_mesh_for_domain(G.X_MIN, G.X_MAX, G.Y_MIN, G.Y_MAX, cell)
    return np.asarray(x), np.asarray(y)


def main():
    fig = plt.figure(figsize=(F.WIDTH, 6.3))
    w, h = 0.36, 0.38
    pos = [(0.08, 0.58), (0.50, 0.58), (0.08, 0.07), (0.50, 0.07)]
    axs = [fig.add_axes([x0, y0, w, h]) for x0, y0 in pos]
    gx, gy = mesh(1.25)
    im = show(axs[0], gx, gy, G.phi_field("gradient", gy), 1.25, *K.MOUTH)
    mx, my = mesh(2.5)
    show(axs[1], mx, my, C.field("band", mx, my, phi_band=0.45, band_x=C.BAND_X_COLLAR), 2.5, *K.MOUTH)
    show(axs[2], mx, my, C.field("random", mx, my, seed=1), 2.5, *K.MOUTH)
    end = G.hole_geometry()[0]
    for ax, t in zip(axs[:3], (u"(a) 孔隙率梯度", u"(b) 贯通通道", u"(c) 随机非均质")):
        F.draw_hole(ax, (0.0, 0.0), (end[0] - K.MOUTH[0], end[1] - K.MOUTH[1]), 0.0)
        ax.set_title(t, fontsize=9)
        ax.set_xlim(0, 60); ax.set_ylim(G.Y_MIN - K.MOUTH[1], G.Y_MAX - K.MOUTH[1])
        ax.set_xlabel(u"水平距离 / m", fontsize=8)
        ax.tick_params(labelsize=7)
        K.style(ax)
    for ax in (axs[0], axs[2]):
        ax.set_ylabel(u"相对孔口高程 / m", fontsize=8)
    f = np.load(os.path.join(K.RR, "D", "boulder", "final_A.npz"))
    ax = axs[3]
    x, y = f["x"], f["y"]
    x0 = x.min() - 0.25
    show(ax, x, y, np.where(f["solid"], 0, f["phi"]), 0.5, x0, 0.0, solid=f["solid"])
    src = np.asarray(f["src"], dtype=int)
    ax.plot(x[src] - x0, y[src], "s", color="k", ms=2.5)
    pk = np.asarray(f["pocket"], dtype=bool)
    ax.annotate(u"块石下方凹形空间", (x[pk].mean() - x0, y[pk].mean()), xytext=(10.5, 2.0), fontsize=7.5,
                ha="center", arrowprops=dict(arrowstyle="-", lw=0.5, color=K.INK, shrinkA=1, shrinkB=1))
    sol = np.asarray(f["solid"], dtype=bool)
    top = y[sol].max()
    ax.annotate(u"块石", (x[sol].mean() - x0, top - 0.2), xytext=(3.0, 13.5), fontsize=7.5,
                arrowprops=dict(arrowstyle="-", lw=0.5, color=K.INK, shrinkA=1, shrinkB=1))
    ax.annotate(u"出浆单元", (x[src].mean() - x0, y[src].mean()), xytext=(11.5, 14.0), fontsize=7.5,
                arrowprops=dict(arrowstyle="-", lw=0.5, color=K.INK, shrinkA=1, shrinkB=1))
    ax.set_xlim(0, 16); ax.set_ylim(0, 16)
    ax.set_xticks([0, 4, 8, 12, 16]); ax.set_yticks([0, 4, 8, 12, 16])
    ax.set_title(u"(d) 架空块石（16 m × 16 m）", fontsize=9)
    ax.set_ylabel(u"高程 / m", fontsize=8)
    ax.set_xlabel(u"水平距离 / m", fontsize=8)
    ax.tick_params(labelsize=7)
    K.style(ax)
    cax = fig.add_axes([0.89, 0.25, 0.015, 0.5])
    cb = fig.colorbar(im, cax=cax, ticks=[0.0, 0.1, 0.2, 0.3, 0.4])
    cb.set_label(u"孔隙率 $n$（≥ 0.45 同色）", fontsize=8)
    cb.ax.tick_params(labelsize=7)
    F.save(fig, "fig_4_1_2")
    print("(d) solid cells %d, pocket cells %d, source cells %d" % (sol.sum(), pk.sum(), len(src)))


if __name__ == "__main__":
    main()
